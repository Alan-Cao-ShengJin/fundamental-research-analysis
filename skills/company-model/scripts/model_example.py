    sh.put('M5', 'Notes', bold=True)
    labels = [f'{y}-{m:02d}' for y in (2024, 2025, 2026) for m in range(1, 13)][:33]
    qlabels = [f'{n}Q{y}' for y in (24, 25, 26) for n in (1, 2, 3, 4)][:11]
    sh.reserve('_m ' + ' '.join(f'm{i}' for i in range(33)) + ' . _q ' + ' '.join(qlabels)
               + ' . _a y2024 y2025 y9m26 ar2024 d2024 ar2025 d2025')
    sh.section('_m', 'MONTHLY SALES VOLUME, UNITS')
    series = {k: [x for v in t[k] for x in months(v)] for k in ['dom', 'exp', 'light', 'ind_dom', 'ind_exp']}

    def shares(r):
        sh.put(f'F{r}', f'=C{r}+D{r}+E{r}', fmt='#,##0')
        sh.put(f'I{r}', f'=C{r}/G{r}', pct=True)
        sh.put(f'J{r}', f'=D{r}/H{r}', pct=True)
        sh.put(f'K{r}', f'=C{r}+D{r}+E{r}-F{r}', fmt='#,##0')
    for i, m in enumerate(labels):
        r = sh.R[f'm{i}']
        sh.put(f'B{r}', m)
        for c, k in zip('CDEGH', ['dom', 'exp', 'light', 'ind_dom', 'ind_exp']):
            sh.put(f'{c}{r}', series[k][i], 'actual', fmt='#,##0')
        shares(r)
    sh.note(sh.R['m0'], 'Company figures from monthly sales announcements; industry from the industry association. '
                        'Months sum to quarters, and domestic, export and light units to the company total.')
    sh.section('_q', 'QUARTERLY SALES VOLUME, UNITS (sum of months)')
    for i, lab in enumerate(qlabels):
        r, a, b = sh.R[lab], sh.R[f'm{3 * i}'], sh.R[f'm{3 * i + 2}']
        sh.put(f'B{r}', lab)
        for c in 'CDEGH':
            sh.put(f'{c}{r}', f'=SUM({c}{a}:{c}{b})', fmt='#,##0')
        shares(r)
    sh.section('_a', 'ANNUAL TOTALS AND ANNUAL-REPORT RECONCILIATION, UNITS')
    for k, lab, qs in [('y2024', '2024', qlabels[0:4]), ('y2025', '2025', qlabels[4:8]), ('y9m26', '9M2026', qlabels[8:11])]:
        r = sh.R[k]
        sh.put(f'B{r}', lab)
        for c in 'CDEFGH':
            sh.put(f'{c}{r}', '=' + '+'.join(f'{c}{sh.R[x]}' for x in qs), fmt='#,##0')
    for y, extra, qs in [(2024, 150, slice(0, 4)), (2025, 0, slice(4, 8))]:
        r, d = sh.R[f'ar{y}'], sh.R[f'd{y}']
        sh.put(f'B{r}', f'AR {y}')
        sh.put(f'B{d}', f'Diff {y}')
        for c, k in zip('CDE', ['dom', 'exp', 'light']):
            sh.put(f'{c}{r}', sum(t[k][qs]) + (extra if k == 'dom' else 0), 'actual', fmt='#,##0')
