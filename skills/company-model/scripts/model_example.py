    prow(sh, 'exp_mix', '  Export share of heavy units', '%', lambda c, r: f'={S("exp", c)}/{S("heavy", c)}', pct=True)
    prow(sh, 'qshare', '  Quarter share of full-year heavy units', '%',
         lambda c, r: f'={S("heavy", c)}/{S("heavy", YEAR_OF[c])}' if c in QUARTERS else None, pct=True)
