def band_title(values, lo, hi):
    """The band chart states its takeaway, and notes any excluded history the axis clips."""
    R, ch = BANDSHEET.R, BANDSHEET.d['charts'][0]
    pos = values[f'{BAND}!D{R["pos_cons"]}']
    ch['title'] = (f'On consensus EPS the shares trade {abs(pos):.1f} SD {"below" if pos < 0 else "above"} '
                   f'their five-year mean forward P/E')
    out = [v for a, v in values.items() if a.startswith(f'{BAND}!K') and type(v) in (int, float) and not lo <= v <= hi]
    if out:
        ch['note'] = f'Grey: excluded history; {len(out)} months between {min(out):.1f}x and {max(out):.1f}x lie outside the axis.'


def scale_band(values):
    """Scale the band chart's axis to the window and its +/-2 SD lines rather than to excluded peaks."""
    R = BANDSHEET.R
    window = [v for a, v in values.items() if a.startswith(f'{BAND}!J') and type(v) in (int, float)]
    lo = min(window + [values[f'{BAND}!D{R["m2"]}']])
    hi = max(window + [values[f'{BAND}!D{R["p2"]}']])
    return math.floor(lo) - 1, math.ceil(hi) + 1


