def freeze(s):
    """Turn generated history into reported figures and history drivers into the ratios they imply."""
    values = mw.calculate(s)['Base']['cells']
    for sh, r, mode, derive, est in FREEZE:
        cells = sh.d['cells']
        for c in HIST:
            a = f'{c}{r}'
            if a not in cells:
                continue
            new = derive(c, r) if derive and mode in ('driver', 'line') else None
            if new is not None:
                cells[a]['value'], cells[a]['kind'] = new, 'calculation'
            elif mode == 'line':
                v = values[f'{sh.name}!{a}']
                cells[a]['value'] = v
                cells[a]['kind'] = 'input' if c in est else 'actual'


def source_tags():
    """Short source tag beside each period row, from what the row holds once history is frozen."""
    for sh in PERIOD_SHEETS:
        rows = {}
        for a, cell in sh.d['cells'].items():
            col, r = mw.split(a)
            if col in COLS and r > 5:
                rows.setdefault(r, set()).add(cell['kind'])
        for r in sorted(rows):
            kinds = rows[r]
            reported, est = 'actual' in kinds, bool({'input', 'judgment'} & kinds)
            tag = TAGS.get((sh.name, r)) or ('Rep./est.' if reported and est else 'Reports' if reported
                                              else 'Est.' if est else None)
            if tag:
                sh.d['tags'][str(r)] = tag


