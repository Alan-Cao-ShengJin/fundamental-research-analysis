def quarterly_truth():
    """Industry and company quarterly volumes, 1Q24 to 3Q26."""
    t = {k: [] for k in ['ind_dom', 'ind_exp', 'light']}
    for y in (2024, 2025):
        for i in range(4):
            t['ind_dom'].append(round(IND_DOM[y] * SEAS['dom'][i]))
            t['ind_exp'].append(round(IND_EXP[y] * SEAS['exp'][i]))
            t['light'].append(round(LIGHT[y] * SEAS['light'][i]))
    for i in range(3):
        for k, g in [('ind_dom', 'dom'), ('ind_exp', 'exp'), ('light', 'light')]:
            t[k].append(round(t[k][4 + i] * (1 + G26[g][i])))
    sd = [SHARE_DOM[2024]] * 4 + SHARE_DOM[2025] + SHARE_DOM[2026]
    se = [SHARE_EXP[2024]] * 4 + SHARE_EXP[2025] + SHARE_EXP[2026]
    t['dom'] = [round(a * s) for a, s in zip(t['ind_dom'], sd)]
    t['exp'] = [round(a * s) for a, s in zip(t['ind_exp'], se)]
    return t


def months(total):
    a, b = round(total * MONTH_W[0]), round(total * MONTH_W[1])
    return [a, b, total - a - b]


