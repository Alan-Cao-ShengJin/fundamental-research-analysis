    P = lambda c: PREV.get(c, c)   # noqa: E731  opening column; FY2021A uses its own balances
    D = lambda c: S('days', c)     # noqa: E731

    def line(k, label, fn, unit='CNY m', **kw):
        return prow(sh, k, label, unit, fn, **kw)

    r = R['days']
    sh.put(f'B{r}', 'Days in period')
    sh.put(f'C{r}', 'days')
    for c in COLS:
        sh.put(f'{c}{r}', 365 if c in ANNUAL else 91.25, fmt='0.00')
    sh.note(r, 'Documented constant: 365 a year, 91.25 a quarter, used by every days-based schedule.')

    sh.section('_is', 'INCOME STATEMENT')
    line('rev', 'Revenue', lambda c, r: flow(c, r, lambda c: f"={q(RP)}{c}{RR['rev']}"), mode='line', bold=True,
         note='Forecast from Revenue Projection; history is the reported income statement.')
    line('rev_yoy', '  Change on last year', lambda c, r: f'={S("rev", c)}/{S("rev", PRIOR_YEAR[c])}-1'
         if c in PRIOR_YEAR else None, '%', pct=True)
    line('cogs', 'Cost of sales', lambda c, r: flow(c, r, lambda c: f"=-({S('rev', c)}-{q(RP)}{c}{RR['gp']})"), mode='line')
