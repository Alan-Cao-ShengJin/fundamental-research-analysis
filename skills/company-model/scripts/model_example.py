def q(sheet):
    return f"{sheet}!" if sheet.isidentifier() else f"'{sheet}'!"


class Sheet:
    def __init__(self, name, last='X', notes='Z', label_width=46, column_width=11, freeze='D6'):
        self.name, self.r, self.R = name, 6, {}
        self.d = {'lastColumn': last, 'notes': notes, 'labelWidth': label_width, 'columnWidth': column_width,
                  'freeze': freeze, 'sections': [], 'cells': {}}

    def put(self, addr, value, kind='calculation', pct=False, bold=False, fmt=None):
        if value is None:
            return
        c = {'value': value, 'kind': kind}
        if pct:
            c['pct'] = True
        if bold:
            c['bold'] = True
        if fmt:
            c['format'] = fmt
        self.d['cells'][addr] = c

    def reserve(self, order):
        """Give each key a row in order, so rows can refer to rows written later."""
        for k in order.split():
            self.R[k] = self.r
            self.r += 1

    def section(self, k, title):
        r = self.R[k]
        self.put(f'B{r}', title)
        self.d['sections'].append(r)

    def note(self, r, text):
        self.put(f"{self.d['notes']}{r}", text)


FREEZE = []   # (sheet, row, mode, derive, estimated columns)


def prow(sh, k, label, unit, fn, note=None, pct=False, fmt=None, bold=False, mode='total', derive=None, est=(), cols=COLS):
    """One period row. fn(c, r) gives a value or '=formula' per column. After the history is generated,
    mode 'line' freezes history as reported figures, 'driver' replaces history with derive(c, r) and
    'total' keeps the formulas."""
    r = sh.R[k]
    sh.put(f'B{r}', label, bold=bold)
    if unit:
        sh.put(f'C{r}', unit)
    if note:
        sh.note(r, note)
    for c in cols:
        v = fn(c, r)
        if v is None:
            continue
        kind = 'calculation' if mw.is_formula(v) else ('input' if c in FORECAST else 'actual')
        sh.put(f'{c}{r}', v, kind, pct, bold, fmt)
    FREEZE.append((sh, r, mode, derive, set(est)))
    return r


def header(sh, title, units):
    sh.put('B1', 'EXAMPLE CO. | ' + title.upper(), bold=True)
    sh.put('B3', units + ' | ' + LEGEND)
    sh.put('B5', 'Period', bold=True)
    for c, p in {**ANNUAL, **QUARTERS}.items():
        sh.put(f'{c}4', 'Estimate' if c in FORECAST or c in 'IJ' else 'Actual')
        sh.put(f'{c}5', p, bold=True)
    if sh.name != RP:
        sh.put('B2', f'=CHOOSE({q(RP)}$C$2,"Active case: Bear","Active case: Base","Active case: Bull")')


def agg_sum(c, r):
    a, b = AGG[c]
    return f'=SUM({a}{r}:{b}{r})'


def flow(c, r, f):
    """Annual columns with quarters sum them; other columns use f(c)."""
    return agg_sum(c, r) if c in AGG else f(c)


def stock(c, r, f):
    return f'={AGG[c][1]}{r}' if c in AGG else f(c)


def hist(d, c):
    """Synthetic history: annual values by column, reported quarters in order."""
    return d[c] if c in d else d['q'][HQ.index(c)]


def driver(fc, hist_values, ratio):
    """A driver row: forecast assumption, simulated history, and the ratio itself in summed annual columns."""
    def fn(c, r):
        if c in FORECAST:
            return fc(c) if callable(fc) else fc
        if c in AGG:
            return ratio(c)
        return hist(hist_values, c) if isinstance(hist_values, dict) else hist_values
    return fn


