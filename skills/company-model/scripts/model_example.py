    prow(sh, 'exp_rev_mix', '  Export share of vehicle revenue', '%', lambda c, r: f'={S("r_exp", c)}/{S("r_veh", c)}', pct=True)

    sh.section('_gm', 'GROSS MARGIN AND GROSS PROFIT')
    prow(sh, 'gm_base', 'Domestic heavy margin before input-cost change', '%',
         lambda c, r: .152 if c == 'T' else f'={case_("case_domgm")}' if c in FORECAST else None, pct=True,
         note='4Q26E at the 9M26 level; FY2027-28 from the active case.')
    prow(sh, 'steel_eff', 'Input-cost effect on domestic heavy margin', '%',
         lambda c, r: f"=-(1-{S('gm_base', c)})*{q(PRICES)}{c}{PR['share']}*{q(PRICES)}{c}{PR['steel_yoy']}"
         if c in FORECAST else None, pct=True,
         note='Cost-of-sales ratio x steel share of cost x steel price change on last year (Input Prices).')
    for key, label, fc, note in [
            ('dom', 'Domestic heavy gross margin', lambda c: f'={S("gm_base", c)}+{S("steel_eff", c)}',
             'Annual: annual-report segment margin; quarters estimated. Forecast is base margin plus input-cost effect.'),
            ('exp', 'Export heavy gross margin', lambda c: .243 if c == 'K' else .245,
             'Export earns about 10pts more than domestic on price; held near the 9M26 level.'),
            ('light', 'Light-unit gross margin', lambda c: .074, 'Held at the 9M26 level.'),
            ('parts', 'Parts and services gross margin', lambda c: .32, 'Stable aftermarket margin.')]:
        ratio = lambda c, key=key: f'={S("g_" + key, c)}/{S("r_" + key, c)}'  # noqa: E731
        prow(sh, 'm_' + key, label, '%', driver(fc, GM[key], ratio), pct=True, note=note, mode='driver',
             derive=lambda c, r, ratio=ratio: ratio(c))
    for key, label in [('dom', 'Domestic heavy gross profit'), ('exp', 'Export heavy gross profit'),
                       ('light', 'Light-unit gross profit'), ('parts', 'Parts and services gross profit')]:
        prow(sh, 'g_' + key, label, 'RMB m', lambda c, r, key=key: flow(c, r, lambda c: f'={S("r_" + key, c)}*{S("m_" + key, c)}'),
             mode='line', est=est, derive=resid)
    prow(sh, 'gp', 'Group gross profit', 'RMB m', lambda c, r: '=' + '+'.join(S('g_' + k, c) for k in ['dom', 'exp', 'light', 'parts']),
         bold=True)
    prow(sh, 'gm', '  Group gross margin', '%', lambda c, r: f'={S("gp", c)}/{S("rev", c)}', pct=True)
    prow(sh, 'reported_gp', 'Reported gross profit (Statements)', 'RMB m', lambda c, r: f'={S("gp", c)}' if c in HIST else None,
         mode='driver', derive=lambda c, r: f"={q(S3)}{c}{R3['gp']}")
    prow(sh, 'gp_chk', '  Check: model less reported', 'RMB m',
         lambda c, r: f'=ROUND({S("gp", c)}-{S("reported_gp", c)},6)' if c in HIST else None,
         note='Quarterly segment profit is estimated so that segments add up to the reported group figure.')

    sh.section('_ue', 'UNIT ECONOMICS, RMB THOUSAND PER UNIT')
    t3 = lambda k, c: f"{q(S3)}{c}{R3[k]}"  # noqa: E731
    prow(sh, 'opex_ratio', 'Operating costs / revenue (taxes, selling, admin, R&D)', '%', lambda c, r:
         f'=-({t3("tax_s", c)}+{t3("sell", c)}+{t3("admin", c)}+{t3("rd", c)})/{t3("rev", c)}', pct=True,
         note='Allocated to products by revenue: a simplification, stated so.')
