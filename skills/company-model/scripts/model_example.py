    sh.section('_guide', 'GUIDANCE AND MANAGEMENT ANCHORS')
    for k, label, v, note in [('guide_heavy', 'FY2026 heavy-unit sales guidance', 90000, 'Guidance sheet, item 1.'),
                              ('guide_exp', 'FY2026 export guidance', 42000, 'Guidance sheet, item 2.')]:
        r = R[k]
        sh.put(f'B{r}', label)
        sh.put(f'C{r}', 'units')
        sh.put(f'I{r}', v, 'input')
        sh.note(r, note)
        TAGS[(sh.name, r)] = 'Guidance'

