def freeze(s):
    """Turn generated history into reported figures and history drivers into the ratios they imply."""
    values = mw.calculate(s)['Base']['cells']
    for sh, r, mode, derive, est in FREEZE:
        cells = sh.d['cells']
        for c in HIST:
            a = f'{c}{r}'
            if a not in cells:
                continue
            new = derive(c, r) if derive and mode in ('driver', 'line') else None
            if new is not None:
                cells[a]['value'], cells[a]['kind'] = new, 'calculation'
            elif mode == 'line':
                v = values[f'{sh.name}!{a}']
                cells[a]['value'] = v
                cells[a]['kind'] = 'input' if c in est else 'actual'


